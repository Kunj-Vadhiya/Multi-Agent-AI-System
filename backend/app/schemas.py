"""
Pydantic schemas for request and response validation.
Supports Version 3 (Tool Calling) and Version 4 (Multi-Agent coordination).
"""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class ChatRequest(BaseModel):
    """Schema for incoming user chat request supporting thread-based conversations and action confirmation."""

    message: str = Field(
        ...,
        min_length=1,
        description="User query or instruction in natural language.",
        examples=[
            "Research the latest developments in RAG, compare different approaches, "
            "analyze their advantages and limitations, and prepare a structured technical report."
        ],
    )
    thread_id: Optional[str] = Field(
        default=None,
        description="Unique thread identifier to maintain persistent conversation workflow across requests.",
        examples=["thread_abc123"],
    )
    confirm_action: Optional[bool] = Field(
        default=None,
        description="Optional flag to confirm (true) or reject (false) a pending external side effect action.",
    )
    messages: Optional[List[Dict[str, Any]]] = Field(
        default=None,
        description="Optional custom conversation history when editing a past user turn or switching versions.",
    )



class ChatResponse(BaseModel):
    """Schema for outgoing multi-agent response."""

    thread_id: Optional[str] = Field(
        default=None,
        description="Active thread identifier associated with this workflow execution.",
    )
    thread_title: Optional[str] = Field(
        default=None,
        description="Concise topic title summarizing the conversation.",
        examples=["FastAPI Overview"],
    )
    response: str = Field(
        ...,
        description="The finalized report and response generated by the multi-agent system.",
        examples=["# Technical Report: Latest Developments in RAG\n\n## 1. Executive Summary..."],
    )
    status: str = Field(
        default="completed",
        description="Workflow execution status ('completed', 'max_retries_exceeded', 'in_progress', or 'awaiting_confirmation').",
        examples=["completed"],
    )
    plan: Optional[List[str]] = Field(
        default=None,
        description="Subtasks planned by the Supervisor Agent.",
    )
    current_agent: Optional[str] = Field(
        default=None,
        description="Last active agent executing in the workflow.",
    )
    agent_history: Optional[List[Dict[str, Any]]] = Field(
        default=None,
        description="Sequence and completion status of executed specialized agents.",
    )
    research_data: Optional[str] = Field(
        default=None,
        description="Factual research findings gathered by the Research Agent.",
    )
    analysis_data: Optional[str] = Field(
        default=None,
        description="Comparative and analytical evaluations from the Analysis Agent.",
    )
    code_results: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Generated code, explanation, and execution results from Coding Agent.",
    )
    database_results: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Database query and schema inspection results from Database Agent.",
    )
    document_results: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Generated documents or summaries from Document Agent.",
    )
    email_results: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Email drafts or search findings from Email Agent.",
    )
    calendar_results: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Calendar events or availability results from Calendar Agent.",
    )
    rag_context: Optional[str] = Field(
        default=None,
        description="Retrieved RAG document context integrated during research.",
    )
    retrieved_documents: Optional[List[Dict[str, Any]]] = Field(
        default=None,
        description="Metadata and source citations for chunks retrieved from the knowledge base.",
    )
    validation_result: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Structured validation verdict from the Validator Agent.",
    )
    pending_action: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Details of an external side effect action awaiting user confirmation.",
    )
    confirmation_required: Optional[bool] = Field(
        default=None,
        description="Indicates whether the workflow is paused awaiting user confirmation.",
    )
    agent_logs: Optional[List[Dict[str, Any]]] = Field(
        default=None,
        description="Execution trace recording the sequence of agent operations.",
    )


class DocumentUploadResponse(BaseModel):
    """Schema for document upload and ingestion response."""

    document_id: str = Field(
        ...,
        description="Unique identifier assigned to the ingested document.",
        examples=["doc_0a1b2c3d"],
    )
    filename: str = Field(
        ...,
        description="Original name of the uploaded document.",
        examples=["transformers.pdf"],
    )
    chunks_created: int = Field(
        ...,
        description="Total number of text chunks extracted, embedded, and stored.",
        examples=[42],
    )
    status: str = Field(
        default="success",
        description="Ingestion operation outcome status.",
        examples=["success"],
    )


class ValidationOutput(BaseModel):
    """Structured output schema returned by the Validator Agent."""

    status: str = Field(
        ...,
        description="Validation outcome: 'PASS' if the report meets all criteria, 'FAIL' if revisions are needed.",
        examples=["PASS", "FAIL"],
    )
    issues: List[str] = Field(
        default_factory=list,
        description="List of specific flaws, missing aspects, or inconsistencies detected.",
    )
    feedback: str = Field(
        default="",
        description="Constructive guidance for the Writer Agent on how to revise the report.",
    )


class HealthResponse(BaseModel):
    """Schema for health status check."""

    status: str = Field(
        default="healthy",
        description="Current health status of the service.",
        examples=["healthy"],
    )


class RootResponse(BaseModel):
    """Schema for root message response."""

    message: str = Field(
        ...,
        description="Informational message about the running API.",
        examples=["Multi-Agent AI Task Automation API is running"],
    )
